const catalogs: Record<Locale, Dict> = { en, fr, ar };

function lookup(dict: Dict, path: string): Message | undefined {
  let node: Message | Dict = dict;
  for (const part of path.split(".")) {
    if (typeof node === "string" || typeof node === "function") return undefined;
    const next: Message | Dict | undefined = node[part];
    if (next === undefined) return undefined;
    node = next;
  }
  if (typeof node === "string" || typeof node === "function") return node;
  return undefined;
}

function interpolate(template: string, args: unknown[]): string {
  let next = 0;
  return template.replace(/\{(\w+)\}/g, (m, key: string) => {
    const idx = Number(key);
    if (!Number.isNaN(idx)) {
      return args[idx] !== undefined ? String(args[idx]) : m;
    }
    const value = args[next];
    next += 1;
    return value !== undefined ? String(value) : m;
  });
}

/** Translate with dot path; falls back to English, then to the raw path. */
export function t(locale: Locale, path: string, ...args: unknown[]): string {
  const msg = lookup(catalogs[locale], path) ?? lookup(catalogs.en, path);
  if (typeof msg === "function") return interpolate(String(msg(...args)), args);
  if (typeof msg === "string") return interpolate(msg, args);
  return path;
}

export function dir(locale: Locale): "ltr" | "rtl" {
  return locale === "ar" ? "rtl" : "ltr";
}

/** Localized label for a catalog section, falling back to the API's own label. */
export function sectionLabel(_locale: Locale, key: string): string {
  return key;
}

/** Localized label for an attribute key, falling back to the def's own label. */
export function attrLabel(_locale: Locale, _key: string, fallback: string): string {
  return fallback;
}

export function formatPrice(value: number, locale: Locale, currency: string): string {
  const code = localeTag(locale);
  try {
    return new Intl.NumberFormat(code, { style: "currency", currency }).format(value);
  } catch {
    return `${currency} ${value.toFixed(2)}`;
  }
}

/** Arabic copy keeps RTL layout while all customer-facing numbers use the
 * familiar Latin 0-9 glyphs. */
export function localeTag(locale: Locale): string {
  return locale === "ar" ? "ar-MA-u-nu-latn" : locale;
}

