const LocaleContext = createContext<{ locale: Locale; setLocale: (l: Locale) => void } | null>(null);

export function LocaleProvider({
  value,
  children,
}: {
  value: { locale: Locale; setLocale: (l: Locale) => void };
  children: ReactNode;
}) {
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

/** Current storefront language (falls back to "en" outside a Storefront). */
export function useLocale(): Locale {
  return useContext(LocaleContext)?.locale ?? "en";
}

/** Change the storefront language (no-op outside a Storefront). */
export function useSetLocale(): (l: Locale) => void {
  return useContext(LocaleContext)?.setLocale ?? (() => {});
}
