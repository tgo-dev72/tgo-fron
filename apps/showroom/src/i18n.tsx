const DICTS: Record<Locale, Dict> = { en, fr, ar };

const LOCALE_NAMES: Record<Locale, string> = { en: "EN", fr: "FR", ar: "AR" };

export const RTL_LOCALES: Locale[] = ["ar"];

function detectLocale(): Locale {
  try {
    const requested = typeof window !== "undefined"
      ? new URLSearchParams(window.location.search).get("lang") as Locale | null
      : null;
    if (requested && LOCALES.includes(requested)) return requested;
    const saved = localStorage.getItem(STORAGE_KEY) as Locale | null;
    if (saved && LOCALES.includes(saved)) return saved;
    const nav = navigator.language.slice(0, 2).toLowerCase();
    if (nav === "fr" || nav === "ar") return nav;
  } catch {
    /* ignore */
  }
  return "en";
}

function replaceTokens(template: string, params?: Record<string, string>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, k: string) => params[k] ?? `{${k}}`);
}

export function useLocale() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useLocale must be used within <I18nProvider>");
  return ctx;
}

const I18nContext = createContext<{ locale: Locale; setLocale: (l: Locale) => void; t: (key: string, params?: Record<string, string>) => string } | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detectLocale);

  useEffect(() => {
    document.documentElement.dir = RTL_LOCALES.includes(locale) ? "rtl" : "ltr";
    document.documentElement.lang = locale;
    try {
      localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      /* ignore */
    }
  }, [locale]);

  const setLocale = (l: Locale) => setLocaleState(l);

  const t = (key: string, params?: Record<string, string>) =>
    replaceTokens(DICTS[locale][key] ?? DICTS.en[key] ?? key, params);

  return <I18nContext.Provider value={{ locale, setLocale, t }}>{children}</I18nContext.Provider>;
}

export { LOCALES, LOCALE_NAMES };

export function retailLabel(rt: { key: string; label: string } | null | undefined, t: (key: string) => string): string {
  if (!rt) return "—";
  return t(`retail.${rt.key}`) !== `retail.${rt.key}` ? t(`retail.${rt.key}`) : rt.label;
}
