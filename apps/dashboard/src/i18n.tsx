const catalogs: Record<Locale, Dict> = { en, fr, ar };

function lookup(dict: Dict, path: string): Message | undefined {
  let node: Message | Dict = dict;
  for (const part of path.split(".")) {
    if (typeof node === "string") return undefined;
    const next: Message | Dict | undefined = node[part];
    if (next === undefined) return undefined;
    node = next;
  }
  return typeof node === "string" ? node : undefined;
}

function interpolate(template: string, args: unknown[]): string {
  if (args.length === 1 && args[0] !== null && typeof args[0] === "object") {
    const map = args[0] as Record<string, unknown>;
    return template.replace(/\{(\w+)\}/g, (m, key: string) => {
      const value = map[key];
      return value !== undefined ? String(value) : m;
    });
  }
  let next = 0;
  return template.replace(/\{(\w+)\}/g, (m, key: string) => {
    const idx = Number(key);
    if (!Number.isNaN(idx)) return args[idx] !== undefined ? String(args[idx]) : m;
    const value = args[next];
    next += 1;
    return value !== undefined ? String(value) : m;
  });
}

/** Translate with dot path; falls back to English, then to the raw path. */
export function t(locale: Locale, path: string, ...args: unknown[]): string {
  const msg = lookup(catalogs[locale], path) ?? lookup(catalogs.en, path);
  if (typeof msg === "string") return interpolate(msg, args);
  return path;
}

/** Return the translated label for a retail type key, falling back to the API label. */
export function retailLabel(locale: Locale, key: string, fallback: string): string {
  const val = t(locale, `retail.${key}`);
  return val !== `retail.${key}` ? val : fallback;
}

export function dir(locale: Locale): "ltr" | "rtl" {
  return locale === "ar" ? "rtl" : "ltr";
}

export function fmtMoney(amount: number | null | undefined, currency = "MAD", locale: Locale = "en"): string {
  const safe = Number(amount) || 0;
  const symbols: Record<string, string> = { MAD: "MAD", EUR: "€", USD: "$", GBP: "£" };
  const sym = currency === "MAD" && locale === "ar" ? "د.م." : symbols[currency] ?? currency;
  const code = locale === "ar" ? "ar-MA" : locale === "fr" ? "fr-FR" : "en-US";
  try {
    return new Intl.NumberFormat(code, { maximumFractionDigits: 2 }).format(safe) + " " + sym;
  } catch {
    return `${safe.toFixed(2)} ${sym}`;
  }
}

export function timeAgo(iso: string, locale: Locale = "en"): string {
  const diff = Date.now() - new Date(iso).getTime();
  const m = Math.floor(diff / 60000);
  if (m < 1) return locale === "ar" ? "الآن" : locale === "fr" ? "à l'instant" : "just now";
  if (m < 60) return locale === "ar" ? `منذ ${m} د` : locale === "fr" ? `il y a ${m} min` : `${m}m ago`;
  const h = Math.floor(m / 60);
  if (h < 24) return locale === "ar" ? `منذ ${h} س` : locale === "fr" ? `il y a ${h} h` : `${h}h ago`;
  const d = Math.floor(h / 24);
  if (d < 7) return locale === "ar" ? `منذ ${d} يوم` : locale === "fr" ? `il y a ${d} j` : `${d}d ago`;
  try {
    return new Date(iso).toLocaleDateString(locale === "ar" ? "ar" : locale);
  } catch {
    return new Date(iso).toLocaleDateString();
  }
}

