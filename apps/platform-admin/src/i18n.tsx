interface LocaleContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  tr: (key: string, variables?: Variables, fallback?: string) => string;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

function initialLocale(): Locale {
  const saved = window.localStorage.getItem(STORAGE_KEY);
  if (saved === "en" || saved === "fr" || saved === "ar") return saved;
  const browserLocale = window.navigator.language.toLowerCase();
  if (browserLocale.startsWith("ar")) return "ar";
  return browserLocale.startsWith("fr") ? "fr" : "en";
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(initialLocale);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
    document.title = messages[locale]["app.title"];
  }, [locale]);

  const value = useMemo<LocaleContextValue>(() => ({
    locale,
    setLocale,
    tr: (key, variables = {}, fallback) => {
      const template = messages[locale][key] ?? messages.en[key] ?? fallback ?? key;
      return Object.entries(variables).reduce(
        (result, [name, replacement]) => result.split(`{${name}}`).join(String(replacement)),
        template,
      );
    },
  }), [locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useI18n() {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("useI18n must be used inside LocaleProvider");
  return value;
}
